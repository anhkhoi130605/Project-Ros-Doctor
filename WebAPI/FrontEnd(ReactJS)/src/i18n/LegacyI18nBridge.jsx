function translateUiText(source) {
  const leading = source.match(/^\s*/)?.[0] || '';
  const trailing = source.match(/\s*$/)?.[0] || '';
  const value = source.trim();
  if (!value) return source;
  const normalizedValue = value.replace(/\s+/g, ' ');

  const exact = ENGLISH_UI_TEXT.get(value) || ENGLISH_UI_TEXT.get(normalizedValue);
  if (exact) return `${leading}${exact}${trailing}`;

  for (const [pattern, replacement] of DYNAMIC_TRANSLATIONS) {
    if (pattern.test(normalizedValue)) {
      return `${leading}${normalizedValue.replace(pattern, replacement)}${trailing}`;
    }
  }

  return source;
}

function isIgnoredTextNode(node) {
  const parent = node.parentElement;
  return !parent || Boolean(parent.closest('script, style, code, pre, [data-i18n-ignore="true"]'));
}

export default function LegacyI18nBridge() {
  const { i18n } = useTranslation();
  const textRecordsRef = useRef(new Map());
  const attributeRecordsRef = useRef(new Map());

  useEffect(() => {
    const textRecords = textRecordsRef.current;
    const attributeRecords = attributeRecordsRef.current;
    const language = String(i18n.resolvedLanguage || i18n.language || 'vi').split('-')[0];

    const restoreVietnamese = () => {
      textRecords.forEach((source, node) => {
        if (node.isConnected) node.nodeValue = source;
      });
      attributeRecords.forEach((attributes, element) => {
        if (!element.isConnected) return;
        Object.entries(attributes).forEach(([name, source]) => element.setAttribute(name, source));
      });
      textRecords.clear();
      attributeRecords.clear();
    };

    if (language !== 'en') {
      restoreVietnamese();
      return undefined;
    }

    const translateTextNode = (node) => {
      if (isIgnoredTextNode(node)) return;
      const current = node.nodeValue || '';
      const recordedSource = textRecords.get(node);
      const previousEnglish = recordedSource ? translateUiText(recordedSource) : null;
      const source = recordedSource && current === previousEnglish ? recordedSource : current;
      const translated = translateUiText(source);

      if (translated !== source) {
        textRecords.set(node, source);
        if (current !== translated) node.nodeValue = translated;
      } else if (recordedSource && current !== previousEnglish) {
        textRecords.delete(node);
      }
    };

    const translateAttributes = (element) => {
      if (!(element instanceof HTMLElement) || element.closest('[data-i18n-ignore="true"]')) return;
      const tracked = attributeRecords.get(element) || {};
      const nextTracked = { ...tracked };

      ['placeholder', 'title', 'aria-label', 'alt'].forEach((name) => {
        if (!element.hasAttribute(name)) return;
        const current = element.getAttribute(name) || '';
        const oldSource = tracked[name];
        const previousEnglish = oldSource ? translateUiText(oldSource) : null;
        const source = oldSource && current === previousEnglish ? oldSource : current;
        const translated = translateUiText(source);

        if (translated !== source) {
          nextTracked[name] = source;
          if (current !== translated) element.setAttribute(name, translated);
        } else if (oldSource && current !== previousEnglish) {
          delete nextTracked[name];
        }
      });

      if (Object.keys(nextTracked).length) attributeRecords.set(element, nextTracked);
      else attributeRecords.delete(element);
    };

    const scan = (root) => {
      if (!root) return;
      if (root.nodeType === Node.TEXT_NODE) {
        translateTextNode(root);
        return;
      }
      if (!(root instanceof Element) && root !== document.body) return;

      if (root instanceof Element) translateAttributes(root);
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
      let node = walker.nextNode();
      while (node) {
        if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
        else translateAttributes(node);
        node = walker.nextNode();
      }
    };

    scan(document.body);

    const observer = new MutationObserver((mutations) => {
      mutations.forEach((mutation) => {
        if (mutation.type === 'characterData') translateTextNode(mutation.target);
        if (mutation.type === 'attributes') translateAttributes(mutation.target);
        mutation.addedNodes.forEach(scan);
      });
    });

    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: ['placeholder', 'title', 'aria-label', 'alt'],
    });

    return () => observer.disconnect();
  }, [i18n, i18n.language, i18n.resolvedLanguage]);

  return null;
}
